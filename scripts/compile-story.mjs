import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { Compiler } from 'inkjs/compiler/Compiler';
import { validateDialogue } from './validate-dialogue.mjs';
import '../story/campaign/author.mjs';
import '../story/taihua-author.mjs';
import '../story/campaign/v6-author.mjs';
import '../story/longmen-author.mjs';
import '../story/dongting-author.mjs';
import '../story/twelfth-author.mjs';
import '../story/kuhe-author.mjs';
import '../story/qingshi-author.mjs';
import '../story/two-swords-author.mjs';
import '../story/seven-questions-author.mjs';
import '../story/jade-thieves-author.mjs';
import '../story/jade-author.mjs';
import '../story/sea-author.mjs';
import '../story/sea-tide-author.mjs';
import '../story/north-author.mjs';
import '../story/qian-kun-author.mjs';
import '../story/north-notes-author.mjs';
import '../story/dead-ranking-author.mjs';
import '../story/luhua-author.mjs';
import '../story/twelfth-life-author.mjs';
import '../story/luoyang-author.mjs';
import '../story/bamboo-author.mjs';
import '../story/xuanmen-author.mjs';
import '../story/white-stone-author.mjs';
import '../story/beyond-ranking-author.mjs';
import {applyDirectionV6} from '../story/production-direction-v6.mjs';
import {applyDirectionV7} from '../story/production-direction-v7.mjs';
// V6 的表被冻结（north / qian-kun 的 preservation 断言钉了它的 SHA），新篇目的字幕放 V7 表。
applyDirectionV6();
applyDirectionV7();
mkdirSync('src/generated',{recursive:true});
for (const [file, output] of [['main', 'story'], ['duel', 'duel'],['campaign','campaign'],['taihua','taihua'],['campaign-v6','campaign-v6'],['longmen','longmen'],['dongting','dongting'],['twelfth','twelfth'],['kuhe','kuhe'],['qingshi','qingshi'],['two-swords','two-swords'],['seven-questions','seven-questions'],['jade-thieves','jade-thieves'],['jade','jade'],['sea','sea'],['sea-tide','sea-tide'],['north','north'],['qian-kun','qian-kun'],['north-notes','north-notes'],['dead-ranking','dead-ranking'],['luhua','luhua'],['twelfth-life','twelfth-life'],['luoyang','luoyang'],['bamboo','bamboo'],['xuanmen','xuanmen'],['white-stone','white-stone'],['beyond-ranking','beyond-ranking']]) {
  const source = readFileSync(`story/${file}.ink`, 'utf8');
  if (file === 'duel') console.log('Dialogue metadata:', validateDialogue(source));
  if (file === 'campaign') console.log('Campaign metadata:',validateDialogue(source,'campaign.ink'));
  if (file === 'taihua') console.log('Taihua metadata:',validateDialogue(source,'taihua.ink'));
  if (file === 'campaign-v6') console.log('V6 preview metadata:',validateDialogue(source,'campaign-v6.ink'));
  if (file === 'longmen') console.log('Longmen metadata:',validateDialogue(source,'longmen.ink'));
  if (file === 'dongting') console.log('Dongting metadata:',validateDialogue(source,'dongting.ink'));
  if (file === 'twelfth') console.log('Twelfth metadata:',validateDialogue(source,'twelfth.ink'));
  if (file === 'kuhe') console.log('Kuhe metadata:',validateDialogue(source,'kuhe.ink'));
  if (file === 'qingshi') console.log('Qingshi metadata:',validateDialogue(source,'qingshi.ink'));
  if (file === 'two-swords') console.log('Two Swords metadata:',validateDialogue(source,'two-swords.ink'));
  if (file === 'seven-questions') console.log('Seven Questions metadata:',validateDialogue(source,'seven-questions.ink'));
  if (file === 'jade-thieves') console.log('Jade Thieves metadata:',validateDialogue(source,'jade-thieves.ink'));
  if (['qian-kun','north-notes','dead-ranking','luhua','twelfth-life','luoyang','bamboo','xuanmen','white-stone','beyond-ranking'].includes(file)) console.log(file+' metadata:',validateDialogue(source,file+'.ink'));
  if (file === 'north') console.log('North metadata:',validateDialogue(source,'north.ink'));
  if (file === 'sea-tide') console.log('Sea Tide metadata:',validateDialogue(source,'sea-tide.ink'));
  if (file === 'sea') console.log('Sea metadata:',validateDialogue(source,'sea.ink'));
  if (file === 'jade') console.log('Jade metadata:',validateDialogue(source,'jade.ink'));
  const compiler = new Compiler(source);
  let story;
  try { story = compiler.Compile(); }
  catch { throw new Error(`${file}.ink\n${compiler.errors.join('\n')}`); }
  if (compiler.errors.length) throw new Error(compiler.errors.join('\n'));
  writeFileSync(`src/generated/${output}.json`, story.ToJson());
  console.log(`Ink ${file}: ${source.length} source characters; ${compiler.warnings.length} warnings`);
  for (const warning of compiler.warnings) console.warn(warning);
}
